// Renders src/data/schema.ts into:
//   supabase/migrations/20261008120100_kafaa_schema.sql  (tables, checks, FKs, indexes, append-only triggers, grants)
//   supabase/migrations/20261008120300_kafaa_rls.sql     (RLS policies derived from the read/write rules)
//   src/data/types.gen.ts                                (row types)
import { writeFileSync, mkdirSync } from 'node:fs';
import { SCHEMA, columnsOf, sqlName } from '../src/data/schema.ts';
import { PLATFORM_ROLES, MIN_GROUP_SIZE } from '../src/auth/policy.ts';

const HEAD = (title) => `-- ${title}\n-- GENERATED by scripts/gen-schema.mjs from src/data/schema.ts. Do not edit by hand: change the schema and run \`npm run gen\`.\n-- Additive only: creates kafaa_* objects; never alters or drops existing NEXUS objects.\n\n`;

const SQLTYPE = { text: 'text', int: 'integer', num: 'numeric', bool: 'boolean', date: 'date', ts: 'timestamptz', json: 'jsonb', 'text[]': 'text[]' };
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

function sqlDefault(c) {
  if (c.def === undefined) return '';
  const d = c.def;
  if (d === 'now') return ' default now()';
  if (c.type === 'json') return ` default ${lit(d)}::jsonb`;
  if (c.type === 'text[]') return d === '[]' ? " default '{}'::text[]" : ` default ${lit(d)}::text[]`;
  if (d.startsWith("'")) return ` default ${d}`;
  return ` default ${d}`;
}

const tables = Object.entries(SCHEMA).filter(([, t]) => !t.localOnly);
let ddl = HEAD("Kafa'a schema: every kafaa_* table");
ddl += `create table if not exists kafaa_schema_version (id int primary key, generated_at timestamptz not null default now(), tables int not null);\nalter table kafaa_schema_version enable row level security;\ndrop policy if exists kafaa_read on kafaa_schema_version;\ncreate policy kafaa_read on kafaa_schema_version for select to anon, authenticated using (true);\ngrant select on kafaa_schema_version to anon, authenticated;\n\n`;
let fks = '';
let idx = '';
for (const [name, t] of tables) {
  const cols = columnsOf(name);
  const lines = cols.map((c) => {
    let s = `  ${c.name} ${SQLTYPE[c.type]}`;
    if (!SQLTYPE[c.type]) throw new Error(`unknown type ${c.type} in ${name}.${c.name}`);
    if (c.pk) s += ' primary key';
    else if (!c.nullable) s += ' not null';
    s += sqlDefault(c);
    if (c.uniq) s += ' unique';
    if (c.enumValues) s += ` check (${c.name} in (${c.enumValues.map(lit).join(', ')}))`;
    return s;
  });
  if (name === 'role_assignments') lines.push(`  constraint kafaa_role_assignments_role_chk check (role in (${PLATFORM_ROLES.map(lit).join(', ')}))`);
  ddl += `-- ${t.module} · ${t.label}\ncreate table if not exists ${sqlName(name)} (\n${lines.join(',\n')}\n);\n`;
  ddl += `comment on table ${sqlName(name)} is ${lit(`[${t.module}] ${t.label}`)};\n\n`;
  for (const c of cols) {
    if (c.ref) {
      fks += `do $$ begin if not exists (select 1 from pg_constraint where conname = '${sqlName(name)}_${c.name}_fk') then alter table ${sqlName(name)} add constraint ${sqlName(name)}_${c.name}_fk foreign key (${c.name}) references ${sqlName(c.ref)}(id) deferrable initially deferred; end if; end $$;\n`;
    }
    if (c.idx || (c.ref && !c.pk && !c.uniq)) idx += `create index if not exists ${sqlName(name)}_${c.name}_idx on ${sqlName(name)} (${c.name});\n`;
  }
}
ddl += `-- Foreign keys (deferrable so seed data can load in any order inside one transaction)\n${fks}\n-- Indexes\n${idx}\n`;

// Append-only tables: no update/delete through any interface, including SECURITY DEFINER functions.
ddl += `create or replace function kafaa_append_only() returns trigger language plpgsql set search_path = public as $$
begin
  raise exception 'Kafa''a · % is append-only: corrections create a new entry with a reason', tg_table_name using errcode = '42501';
end $$;\n`;
for (const [name, t] of tables) {
  if (t.write.mode === 'append') {
    ddl += `drop trigger if exists ${sqlName(name)}_append_only on ${sqlName(name)};\ncreate trigger ${sqlName(name)}_append_only before update or delete on ${sqlName(name)} for each row execute function kafaa_append_only();\n`;
  }
}
ddl += `\ninsert into kafaa_schema_version (id, tables) values (1, ${tables.length}) on conflict (id) do update set generated_at = now(), tables = excluded.tables;\n`;

// ───────────── RLS
let rls = HEAD("Kafa'a row-level security, derived from the read/write rules in src/data/schema.ts and the matrix in src/auth/policy.ts");
const ruleExpr = (r) => {
  const person = r.person ? r.person : 'null::text';
  const org = r.org ? r.org : 'null::text';
  const where = r.where ? r.where : 'true';
  const res = lit(r.res);
  if (r.special === 'agg_ok') return `kafaa_has_grant(${res}, array['Agg','R','W','A'])`;
  if (r.special === 'agg_suppressed') return `(kafaa_has_grant(${res}, array['R','W','A']) or (kafaa_has_grant(${res}, array['Agg']) and group_size >= ${MIN_GROUP_SIZE}))`;
  if (r.special === 'university_consent') return `(kafaa_rule_read(${res}, ${person}, ${org}, ${where}) or (kafaa_role_grant('university', ${res}, 'Scope') and university_org_id = kafaa_my_org() and consent_university))`;
  if (r.special === 'observer_org') return `(kafaa_has_grant(${res}, array['Agg']) and status = 'released' and kafaa_my_org() = any(released_to_org_ids))`;
  return `kafaa_rule_read(${res}, ${person}, ${org}, ${where})`;
};
for (const [name, t] of tables) {
  const tn = sqlName(name);
  rls += `-- ${name}\nalter table ${tn} enable row level security;\n`;
  rls += `drop policy if exists kafaa_read on ${tn};\ncreate policy kafaa_read on ${tn} for select to anon, authenticated using (${t.read.map(ruleExpr).join('\n    or ')});\n`;
  const w = t.write;
  let grants = 'select';
  if (w.mode === 'direct') {
    const res = lit(w.res);
    const pcol = (t.read.find((r) => r.person) || {}).person;
    const ocol = (t.read.find((r) => r.org) || {}).org;
    const terms = [`kafaa_has_grant(${res}, array['W','A'])`];
    if (w.own && pcol) terms.push(`(${pcol} = kafaa_me() and kafaa_has_grant(${res}, array['Own','Scope']))`);
    if (w.orgw && ocol) terms.push(`(${ocol} = kafaa_my_org() and kafaa_has_grant(${res}, array['OrgW']))`);
    const check = terms.join(' or ');
    rls += `drop policy if exists kafaa_insert on ${tn};\ncreate policy kafaa_insert on ${tn} for insert to anon, authenticated with check (${w.anonInsert ? 'true' : check});\n`;
    rls += `drop policy if exists kafaa_update on ${tn};\ncreate policy kafaa_update on ${tn} for update to authenticated using (${check}) with check (${check});\n`;
    grants = w.anonInsert ? 'select, insert' : 'select, insert, update';
    rls += `grant ${grants} on ${tn} to authenticated;\ngrant ${w.anonInsert ? 'select, insert' : 'select'} on ${tn} to anon;\n`;
    rls += `drop trigger if exists ${tn}_audit on ${tn};\ncreate trigger ${tn}_audit after insert or update on ${tn} for each row execute function kafaa_audit_row();\n\n`;
  } else {
    rls += `grant select on ${tn} to anon, authenticated;\n-- writes: ${w.mode === 'rpc' ? 'only through SECURITY DEFINER kafaa_* RPCs (consequential action, ledger)' : w.mode === 'append' ? 'append-only, through kafaa_audit() / RPCs' : 'reference data, no client writes'}\n\n`;
  }
}

// ───────────── TS types
const TSTYPE = { text: 'string', int: 'number', num: 'number', bool: 'boolean', date: 'string', ts: 'string', json: 'any', 'text[]': 'string[]' };
const pascal = (s) => s.split('_').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
let ts = `// GENERATED by scripts/gen-schema.mjs from src/data/schema.ts. Do not edit by hand.\n/* eslint-disable */\n`;
const map = [];
for (const [name] of Object.entries(SCHEMA)) {
  const cols = columnsOf(name);
  ts += `export interface ${pascal(name)}Row {\n`;
  for (const c of cols) {
    const ty = c.enumValues ? c.enumValues.map((v) => `'${v}'`).join(' | ') : TSTYPE[c.type];
    ts += `  ${c.name}${c.nullable ? '?' : ''}: ${ty}${c.nullable ? ' | null' : ''};\n`;
  }
  ts += `}\n`;
  map.push(`  ${name}: ${pascal(name)}Row;`);
}
ts += `\nexport interface Tables {\n${map.join('\n')}\n}\nexport type Table = keyof Tables;\nexport type RowOf<T extends Table> = Tables[T];\n`;

mkdirSync('supabase/migrations', { recursive: true });
writeFileSync('supabase/migrations/20261008120100_kafaa_schema.sql', ddl);
writeFileSync('supabase/migrations/20261008120300_kafaa_rls.sql', rls);
writeFileSync('src/data/types.gen.ts', ts);
console.log(`gen-schema: ${tables.length} SQL tables, ${Object.keys(SCHEMA).length} TS row types`);
