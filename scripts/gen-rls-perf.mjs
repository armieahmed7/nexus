// Generates supabase/migrations/20261008140000_kafaa_rls_perf.sql: the same RLS rules, evaluated once per query.
//
// Every kafaa_* policy calls SECURITY DEFINER helpers (kafaa_rule_read → kafaa_has_grant → kafaa_my_roles → kafaa_me →
// nexus_my_persona). Postgres cannot inline those, so each was re-run for every row: kafaa_people (5 rules × 345 rows)
// hit the 3 s anon / 8 s authenticated statement timeouts. This script applies all earlier migrations to PGlite, reads
// the resulting policies, and rewrites each expression so the caller-only parts become scalar sub-selects
// ("(select kafaa_has_grant(...))", "(select kafaa_me())"), which Postgres evaluates once per statement (InitPlan).
// kafaa_rule_read(res, person, org, where) is expanded inline with exactly its own logic; the per-row scope test stays a
// (gated) kafaa_rule_read call because kafaa_in_scope is not executable by API roles.
//
// It then proves equivalence: for every test identity × every kafaa_* table the visible row set (md5 of ids) must be the
// same before and after the rewrite, and the output uses ALTER POLICY only (no policy is removed or recreated).
//   node scripts/gen-rls-perf.mjs            write the migration
//   node scripts/gen-rls-perf.mjs --check    fail if the committed migration is out of date
import { PGlite } from '@electric-sql/pglite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const OUT = '20261008140000_kafaa_rls_perf.sql';
const read = (p) => readFileSync(p, 'utf8');
const migs = readdirSync('supabase/migrations').filter((f) => f.endsWith('.sql') && f < OUT).sort();

const db = new PGlite();
await db.exec(read('supabase/tests/nexus_stubs.sql'));
for (const m of migs) await db.exec(read(`supabase/migrations/${m}`));
await db.exec(read('supabase/seed.sql'));

// ── rewrite
const RES = `'([a-z_]+)'::text`;
const ARG = `(NULL::text|[a-z_][a-z0-9_]*)`;
const BOOL = `(true|false|[a-z_][a-z0-9_]*)`;
const ruleRe = new RegExp(`kafaa_rule_read\\(${RES}, ${ARG}, ${ARG}, ${BOOL}\\)`, 'g');
const grant = (res, levels) => `(SELECT kafaa_has_grant('${res}'::text, ARRAY[${levels.map((l) => `'${l}'::text`).join(', ')}]))`;
function expandRule(_m, res, person, org, where) {
  const terms = [];
  const w = where === 'true' ? '' : where === 'false' ? null : `COALESCE(${where}, false) AND `;
  if (w !== null) terms.push(`(${w}${grant(res, ['R', 'W', 'A'])})`);
  if (person !== 'NULL::text') {
    terms.push(`((${person} = (SELECT kafaa_me())) AND ${grant(res, ['Own', 'Scope'])})`);
    // kafaa_in_scope is not executable by anon/authenticated (grants hardening), so the per-row scope test goes through
    // kafaa_rule_read itself (SECURITY DEFINER, where = false, org = null), and only when the caller holds a Scope grant.
    terms.push(`(${grant(res, ['Scope'])} AND kafaa_rule_read('${res}'::text, ${person}, NULL::text, false))`);
  }
  if (org !== 'NULL::text') terms.push(`((${org} = (SELECT kafaa_my_org())) AND ${grant(res, ['OwnOrg', 'OrgW'])})`);
  return terms.length ? `(${terms.join(' OR ')})` : 'false';
}
export function rewrite(expr) {
  if (expr == null) return expr;
  let s = expr.replace(ruleRe, expandRule);
  if (/kafaa_rule_read\((?!'[a-z_]+'::text, [a-z_][a-z0-9_]*, NULL::text, false\))/.test(s)) throw new Error(`unrecognised kafaa_rule_read call in: ${expr}`);
  // Wrap the remaining caller-only helpers (no row arguments) that are not already inside a sub-select.
  s = s.replace(/(?<!SELECT )kafaa_has_grant\('[a-z_]+'::text, ARRAY\[[^\]]*\]\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_role_grant\('[a-z_]+'::text, '[a-z_]+'::text, '[A-Za-z]+'::text\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_has_role\('[a-z_]+'::text\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_me\(\)/g, '(SELECT kafaa_me())');
  s = s.replace(/(?<!SELECT )kafaa_my_org\(\)/g, '(SELECT kafaa_my_org())');
  return s;
}

const pols = (await db.query(`select tablename, policyname, cmd, qual, with_check from pg_policies where schemaname = 'public' and tablename like 'kafaa\\_%' order by tablename, policyname`)).rows;
let sql = `-- GENERATED by scripts/gen-rls-perf.mjs. Do not edit by hand.
-- Kafa'a RLS performance: the same rules, with caller-only helpers evaluated once per statement instead of once per row.
-- ALTER POLICY only: no policy is removed or recreated, and every rule keeps its meaning (checked by the generator
-- against every test identity and every kafaa_* table). Idempotent: re-running sets the same expressions again.
`;
let n = 0;
for (const p of pols) {
  const q = rewrite(p.qual);
  const c = rewrite(p.with_check);
  if (q === p.qual && c === p.with_check) continue;
  const parts = [];
  if (p.qual != null) parts.push(`using (${q})`);
  if (p.with_check != null) parts.push(`with check (${c})`);
  sql += `alter policy ${p.policyname} on public.${p.tablename} ${parts.join(' ')};\n`;
  n++;
}
for (const bad of ['drop ', 'delete ', 'truncate ']) if (sql.toLowerCase().includes(bad)) throw new Error(`generated SQL contains "${bad.trim()}"`);

// ── equivalence check: visible rows per identity × table, before vs after
const tables = (await db.query(`select tablename from pg_tables where schemaname = 'public' and tablename like 'kafaa\\_%' order by 1`)).rows.map((r) => r.tablename);
// A spread of identities: every platform role, partner orgs, crew/team scopes, self-only staff, and anonymous.
const people = ['nse', 'chem-sup', 'presenter', 'chco', 'training-mgr', 'sq-lead', 'head-sustainability', 'ai-governance', 'sro', 'rao', 'alnoor-gm', 'alnoor-qaqc',
  'gulfhydro-qa', 'k-student', 'k-university', 'k-observer', 'k-ecp', 'k-ro', 'k-lo-trainee', 'k-instructor', 'k-hr-analyst', 'k-contractor', 'k-auditor', 'k-licensing-coord'];
const ids = [null];
let i = 0;
for (const persona of people) {
  const uid = `00000000-0000-4000-8000-${String(700 + ++i).padStart(12, '0')}`;
  await db.query(`insert into profiles (user_id, email, persona_id, org_id, lens, roles) select $1, $2, $3, coalesce(p.org_id, 'enec-ops'), 'employee', array['Test'] from kafaa_people p where p.persona_id = $3 limit 1 on conflict do nothing`, [uid, `${persona}@perf.test`, persona]);
  ids.push(uid);
}
async function snapshot() {
  const out = {};
  for (const uid of ids) {
    await db.exec('reset role');
    await db.query(`select set_config('request.jwt.claims', $1, false)`, [uid ? JSON.stringify({ sub: uid }) : '']);
    await db.exec(uid ? 'set role authenticated' : 'set role anon');
    for (const t of tables) {
      try {
        const r = (await db.query(`select count(*)::int n, md5(coalesce(string_agg(id::text, ',' order by id::text), '')) h from ${t}`)).rows[0];
        out[`${uid ?? 'anon'}|${t}`] = `${r.n}:${r.h}`;
      } catch (e) {
        out[`${uid ?? 'anon'}|${t}`] = `error:${e.message}`;
      }
    }
    await db.exec('reset role');
    process.stdout.write('.');
  }
  process.stdout.write('\n');
  return out;
}
const before = await snapshot();
await db.exec(sql);
const after = await snapshot();
const diffs = Object.keys(before).filter((k) => before[k] !== after[k]);
const visible = Object.values(before).filter((v) => !v.startsWith('0:') && !v.startsWith('error')).length;
if (diffs.length) {
  console.error(`gen-rls-perf: ${diffs.length} identity×table results changed:\n${diffs.slice(0, 20).map((k) => `  ${k}: ${before[k]} -> ${after[k]}`).join('\n')}`);
  process.exit(1);
}
console.log(`gen-rls-perf: ${n} policies rewritten; ${ids.length} identities × ${tables.length} tables identical before/after (${visible} non-empty results)`);

const path = `supabase/migrations/${OUT}`;
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = read(path);
  } catch {
    /* missing */
  }
  if (cur !== sql) {
    console.error(`gen-rls-perf: ${path} is out of date; run node scripts/gen-rls-perf.mjs`);
    process.exit(1);
  }
} else writeFileSync(path, sql);
