// Generates, from the route definitions in src/modules/*/routes.ts (the router's own guards, in src/routes/registry.ts order):
//   src/routes/guards.gen.ts                                       import-free [path, guard] list for code that runs outside React
//                                                                 (the digest rules, the seed builder, the PGlite validators)
//   supabase/migrations/20261013200005_kafaa_ready_route_guards.sql kafaa_route_guard(path) + kafaa_route_ok_for(person, link, day): the
//                                                                 same guard check in SQL, so kafaa_dg_compute drops digest items whose
//                                                                 link the person cannot open (readiness fixes 2026-10-13, finding 2)
//   tests/fixtures/routes.manifest.json                            every route's id, path, module, zone and guard in router order: the one
//                                                                 place tests read the route total from; tests/unit/route-manifest.test.ts
//                                                                 diffs the live registry against it (TECH-09, 2026-10-17)
// tests/unit/ready-route-guards.test.ts checks that guards.gen.ts equals the live ROUTES registry (so this parser cannot drift).
//   node scripts/gen-route-guards.mjs           write all three files
//   node scripts/gen-route-guards.mjs --check   fail if any of them is out of date
import { readFileSync, writeFileSync } from 'node:fs';

const TS_OUT = 'src/routes/guards.gen.ts';
const SQL_OUT = 'supabase/migrations/20261013200005_kafaa_ready_route_guards.sql';
const MANIFEST_OUT = 'tests/fixtures/routes.manifest.json';

const reg = readFileSync('src/routes/registry.ts', 'utf8');
const imports = Object.fromEntries([...reg.matchAll(/import \{ routes as (m\d+) \} from '\.\.\/modules\/(m\d+)\/routes';/g)].map((m) => [m[1], m[2]]));
const order = [...reg.match(/export const ROUTES: RouteDef\[\] = \[([^\]]*)\]/)[1].matchAll(/\.\.\.(m\d+)/g)].map((m) => m[1]);
if (!order.length || order.some((m) => !imports[m])) throw new Error('gen-route-guards: cannot read the ROUTES order from src/routes/registry.ts');

// Each routes.ts imports only `lazy` from react and the RouteDef type: transpile it with TypeScript and evaluate it with a stub `lazy`,
// so guard constants (const OWN = {...}) resolve exactly as in the app.
const ts_ = (await import('typescript')).default;
const list = [];
const manifest = [];
for (const m of order) {
  const src = readFileSync(`src/modules/${imports[m]}/routes.ts`, 'utf8');
  const js = ts_.transpileModule(src, { compilerOptions: { module: ts_.ModuleKind.ESNext, target: ts_.ScriptTarget.ES2020 } }).outputText
    .replace(/^import .*$/gm, '')
    .replace(/export const routes\b/, 'const routes');
  const routes = Function('lazy', `"use strict"; ${js}; return routes;`)(() => null);
  for (const r of routes) {
    const guard = r.guard ?? {};
    const g = {};
    if (guard.signedIn) g.signedIn = true;
    if (guard.anyRole) g.anyRole = [...guard.anyRole];
    if (guard.grant) g.grant = { res: guard.grant.res, levels: [...guard.grant.levels] };
    if (guard.noTelemetry) g.noTelemetry = true;
    list.push([r.path, g]);
    manifest.push({ id: r.id, path: r.path, module: r.module, zone: r.zone, guard: g });
  }
}

const ts = `// GENERATED by scripts/gen-route-guards.mjs from src/modules/*/routes.ts (npm run gen). Do not edit by hand.
// Every route's path and guard, in router order (src/routes/registry.ts), import-free for code that runs outside React (the digest rules,
// the seed builder, the PGlite validators). src/routes/linkAccess.ts matches a link against it; SQL mirror kafaa_route_guard().
export interface GuardLite { signedIn?: boolean; anyRole?: string[]; grant?: { res: string; levels: string[] }; noTelemetry?: boolean }
export const ROUTE_GUARDS: [string, GuardLite][] = [
${list.map(([p, g]) => `  [${JSON.stringify(p)}, ${JSON.stringify(g)}],`).join('\n')}
];
`;

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const reOf = (p) => `^${p.replace(/[.+^$()|[\]\\]/g, '\\$&').replace(/:[A-Za-z0-9_]+/g, '[^/]+')}$`;
// static paths first, then parameter paths, each in router order (= routeForPath)
const ranked = [...list.map((x, i) => [...x, i])].sort((a, b) => Number(a[0].includes(':')) - Number(b[0].includes(':')) || a[2] - b[2]);
const sql = `-- GENERATED by scripts/gen-route-guards.mjs from src/modules/*/routes.ts (npm run gen). Do not edit by hand.
-- [Readiness fixes 2026-10-13 · finding 2] The router's route guards in SQL, so the weekly digest only offers items the person can open.
--   kafaa_route_guard(path)                  the guard of the route a path opens (static paths before parameter paths, router order,
--                                            case-insensitive like React Router's matchPath), null for an unknown path
--   kafaa_route_ok_for(person, link, day)    = checkGuard() in src/auth/guards.tsx for that person signed in on that day: public routes are
--                                            open; signedIn needs a person; anyRole / grant read the person's active role assignments
--                                            (plus 'public') and kafaa_policy_matrix, like kafaa_my_roles() / kafaa_has_grant()
-- TS mirror: src/routes/linkAccess.ts (linkOpenFor) over src/routes/guards.gen.ts. Both helpers are internal (no API role executes them).
-- Idempotent (create or replace). Touches no table.

create or replace function kafaa_route_guard(p_path text) returns jsonb language sql immutable set search_path = public as $$
  select v.g from (values
${ranked.map(([p, g], k) => `    (${k + 1}, ${lit(reOf(p))}, ${lit(JSON.stringify(g))}::jsonb)`).join(',\n')}
  ) v(ord, re, g)
  where p_path ~* v.re
  order by v.ord
  limit 1
$$;

create or replace function kafaa_route_ok_for(p_person text, p_link text, p_day date) returns boolean language plpgsql stable security definer set search_path = public as $$
declare v_path text; g jsonb; v_roles text[];
begin
  if p_link is null or left(p_link, 1) <> '/' or left(p_link, 2) = '//' then return false; end if;
  v_path := split_part(split_part(p_link, '#', 1), '?', 1);
  if v_path = '' then v_path := '/'; end if;
  if v_path = '/ar' or v_path like '/ar/%' then v_path := coalesce(nullif(substr(v_path, 4), ''), '/'); end if;
  if length(v_path) > 1 and right(v_path, 1) = '/' then v_path := left(v_path, -1); end if;
  g := kafaa_route_guard(v_path);
  if g is null then return false; end if;
  if not (coalesce((g ->> 'signedIn')::boolean, false) or g ? 'anyRole' or g ? 'grant') then return true; end if;
  if p_person is null then return false; end if;
  if not (g ? 'anyRole' or g ? 'grant') then return true; end if;
  select array_append(coalesce(array_agg(distinct ra.role), '{}'::text[]), 'public') into v_roles
    from kafaa_role_assignments ra
   where ra.person_id = p_person and ra.status = 'active' and (ra.expires_at is null or ra.expires_at >= p_day);
  return (g ? 'anyRole' and exists (select 1 from jsonb_array_elements_text(g -> 'anyRole') r(x) where r.x = any(v_roles)))
      or (g ? 'grant' and exists (select 1 from kafaa_policy_matrix m
                                   where m.resource = g -> 'grant' ->> 'res' and m.role = any(v_roles)
                                     and m.level in (select jsonb_array_elements_text(g -> 'grant' -> 'levels'))));
end $$;

revoke all on function kafaa_route_guard(text), kafaa_route_ok_for(text, text, date) from public, anon, authenticated;
`;

// One route per line, so adding or removing a route is a one-line diff (and a one-line merge conflict at most).
const json = `[\n${manifest.map((r) => `  ${JSON.stringify(r)}`).join(',\n')}\n]\n`;

let stale = 0;
for (const [path, body] of [[TS_OUT, ts], [SQL_OUT, sql], [MANIFEST_OUT, json]]) {
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (cur !== body) { console.error(`gen-route-guards: ${path} is out of date; run npm run gen`); stale++; }
  } else writeFileSync(path, body);
}
if (stale) process.exit(1);
console.log(`gen-route-guards: ${list.length} routes${process.argv.includes('--check') ? ' (up to date)' : ''}`);
