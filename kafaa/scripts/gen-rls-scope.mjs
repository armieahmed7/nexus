// Generates supabase/migrations/20261013200002_kafaa_ready_rls_scope.sql (readiness fixes 2026-10-13, finding 3): the same RLS rules
// without a SECURITY DEFINER call per row.
//
// 20261008140000_kafaa_rls_perf.sql (scripts/gen-rls-perf.mjs) already evaluates the caller-only helpers once per statement, but left the
// per-row scope test "kafaa_rule_read(res, person_id, null, false)" (161 SELECT policies on live), and policies written after it by the
// FS waves call kafaa_rule_read(res, null, null, true) and friends per row. This script applies every earlier migration and the seed to
// PGlite, reads the policies and rewrites every kafaa_rule_read(res, person, org, where) call with exactly its own logic:
//   where   -> (coalesce(where, false) and (select kafaa_has_grant(res, R/W/A)))
//   person  -> (person = any ((select kafaa_scope_people(res))::text[])) the caller (Own/Scope) and the people in their Scope assignments,
//                                                                    one InitPlan per statement (20261013200001_kafaa_ready_scope_people.sql)
//   org     -> ((org = (select kafaa_my_org())) and (select kafaa_has_grant(res, OwnOrg/OrgW)))
// then wraps any remaining caller-only helper in a scalar sub-select, as gen-rls-perf does. It proves equivalence: for every test identity
// x every kafaa_* table the visible row set (count and md5 of the ids) is the same before and after, and the output uses ALTER POLICY only.
//   node scripts/gen-rls-scope.mjs            write the migration
//   node scripts/gen-rls-scope.mjs --check    fail if the committed migration is out of date
import { PGlite } from '@electric-sql/pglite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const OUT = '20261013200002_kafaa_ready_rls_scope.sql';
const read = (p) => readFileSync(p, 'utf8');
const migs = readdirSync('supabase/migrations').filter((f) => f.endsWith('.sql') && f < OUT).sort();

const db = new PGlite();
await db.exec(read('supabase/tests/nexus_stubs.sql'));
for (const m of migs) await db.exec(read(`supabase/migrations/${m}`));
await db.exec(read('supabase/seed.sql'));

// ── rewrite
const RES = `'([a-z_]+)'::text`;
const ARG = `(NULL::text|[a-z_][a-z0-9_]*)`;
const BOOL = `(true|false|[a-z_][a-z0-9_]*)`;
const ruleRe = new RegExp(`kafaa_rule_read\\(${RES}, ${ARG}, ${ARG}, ${BOOL}\\)`, 'g');
const grant = (res, levels) => `(SELECT kafaa_has_grant('${res}'::text, ARRAY[${levels.map((l) => `'${l}'::text`).join(', ')}]))`;
function expandRule(_m, res, person, org, where) {
  const terms = [];
  if (where === 'true') terms.push(grant(res, ['R', 'W', 'A']));
  else if (where !== 'false') terms.push(`(COALESCE(${where}, false) AND ${grant(res, ['R', 'W', 'A'])})`);
  if (person !== 'NULL::text') terms.push(`(${person} = ANY ((SELECT kafaa_scope_people('${res}'::text))::text[]))`);
  if (org !== 'NULL::text') terms.push(`((${org} = (SELECT kafaa_my_org())) AND ${grant(res, ['OwnOrg', 'OrgW'])})`);
  return terms.length ? `(${terms.join(' OR ')})` : 'false';
}
export function rewrite(expr) {
  if (expr == null) return expr;
  let s = expr.replace(ruleRe, expandRule);
  if (/kafaa_rule_read\(/.test(s)) throw new Error(`unrecognised kafaa_rule_read call in: ${expr}`);
  s = s.replace(/(?<!SELECT )kafaa_has_grant\('[a-z_]+'::text, ARRAY\[[^\]]*\]\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_role_grant\('[a-z_]+'::text, '[a-z_]+'::text, '[A-Za-z]+'::text\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_has_role\('[a-z_]+'::text\)/g, (m) => `(SELECT ${m})`);
  s = s.replace(/(?<!SELECT )kafaa_me\(\)/g, '(SELECT kafaa_me())');
  s = s.replace(/(?<!SELECT )kafaa_my_org\(\)/g, '(SELECT kafaa_my_org())');
  return s;
}

const pols = (await db.query(`select tablename, policyname, cmd, qual, with_check from pg_policies where schemaname = 'public' and tablename like 'kafaa\\_%' order by tablename, policyname`)).rows;
// the policy fingerprint, same formula as EXPECTED.md section 0 runs on live (scripts/verify-ready-bundle.mjs POLICY_FINGERPRINT)
const beforeMd5 = (await db.query(`select md5(string_agg(tablename || '|' || policyname || '|' || cmd || '|' || coalesce(qual, '') || '|' || coalesce(with_check, ''), E'\\n' order by tablename collate "C", policyname collate "C")) m
  from pg_policies where schemaname = 'public' and tablename like 'kafaa\\_%'`)).rows[0].m;
let sql = `-- GENERATED by scripts/gen-rls-scope.mjs. Do not edit by hand.
-- [Readiness fixes 2026-10-13 · finding 3] Kafa'a RLS without a SECURITY DEFINER call per row: every kafaa_rule_read(res, person, org, where)
-- in a kafaa_* policy becomes its own logic, with the person test "person = any ((select kafaa_scope_people(res))::text[])" evaluated once per
-- statement (20261013200001_kafaa_ready_scope_people.sql). ALTER POLICY only: no policy is removed or recreated, and every rule keeps its
-- meaning (the generator compares the visible rows of every test identity on every kafaa_* table before and after). Idempotent: a second
-- run sets the same expressions again. Policies before this file (fingerprint, EXPECTED.md section 0): ${beforeMd5}
`;
let n = 0;
for (const p of pols) {
  const q = rewrite(p.qual);
  const c = rewrite(p.with_check);
  if (q === p.qual && c === p.with_check) continue;
  const parts = [];
  if (p.qual != null) parts.push(`using (${q})`);
  if (p.with_check != null) parts.push(`with check (${c})`);
  sql += `alter policy ${p.policyname} on public.${p.tablename} ${parts.join(' ')};\n`;
  n++;
}
for (const bad of ['drop ', 'delete ', 'truncate ']) if (sql.toLowerCase().includes(bad)) throw new Error(`generated SQL contains "${bad.trim()}"`);

// ── equivalence check: visible rows per identity × table, before vs after
const tables = (await db.query(`select tablename from pg_tables where schemaname = 'public' and tablename like 'kafaa\\_%' order by 1`)).rows.map((r) => r.tablename);
// A spread of identities: every platform role, partner orgs, crew/team/entity/family scopes, self-only staff, applicants and anonymous.
const people = ['nse', 'chem-sup', 'presenter', 'chco', 'training-mgr', 'sq-lead', 'head-sustainability', 'ai-governance', 'sro', 'rao', 'alnoor-gm', 'alnoor-qaqc',
  'gulfhydro-qa', 'k-student', 'k-graduate', 'k-university', 'k-observer', 'k-ecp', 'k-ro', 'k-lo-trainee', 'k-instructor', 'k-hr-analyst', 'k-contractor', 'k-auditor',
  'k-licensing-coord', 'k-admin', 'k-editor', 'rp-lead', 'outage-manager', 'work-control', 'ep-manager', 'head-sq', 'dra'];
const ids = [null];
let i = 0;
for (const persona of people) {
  const uid = `00000000-0000-4000-8000-${String(800 + ++i).padStart(12, '0')}`;
  await db.query(`insert into profiles (user_id, email, persona_id, org_id, lens, roles) select $1, $2, $3, coalesce(p.org_id, 'enec-ops'), 'employee', array['Test'] from kafaa_people p where p.persona_id = $3 limit 1 on conflict do nothing`, [uid, `${persona}@scope.test`, persona]);
  if ((await db.query(`select 1 from profiles where user_id = $1`, [uid])).rows.length) ids.push(uid);
}
async function snapshot() {
  const out = {};
  for (const uid of ids) {
    await db.exec('reset role');
    await db.query(`select set_config('request.jwt.claims', $1, false)`, [uid ? JSON.stringify({ sub: uid }) : '']);
    await db.exec(uid ? 'set role authenticated' : 'set role anon');
    for (const t of tables) {
      try {
        const r = (await db.query(`select count(*)::int n, md5(coalesce(string_agg(id::text, ',' order by id::text), '')) h from ${t}`)).rows[0];
        out[`${uid ?? 'anon'}|${t}`] = `${r.n}:${r.h}`;
      } catch (e) {
        out[`${uid ?? 'anon'}|${t}`] = `error:${e.message}`;
      }
    }
    await db.exec('reset role');
    process.stdout.write('.');
  }
  process.stdout.write('\n');
  return out;
}
const snapBefore = await snapshot();
await db.exec(sql);
const snapAfter = await snapshot();
const diffs = Object.keys(snapBefore).filter((k) => snapBefore[k] !== snapAfter[k]);
const visible = Object.values(snapBefore).filter((v) => !v.startsWith('0:') && !v.startsWith('error')).length;
if (diffs.length) {
  console.error(`gen-rls-scope: ${diffs.length} identity×table results changed:\n${diffs.slice(0, 20).map((k) => `  ${k}: ${snapBefore[k]} -> ${snapAfter[k]}`).join('\n')}`);
  process.exit(1);
}
const left = (await db.query(`select count(*)::int n from pg_policies where schemaname = 'public' and tablename like 'kafaa\\_%' and (qual like '%kafaa_rule_read(%' or with_check like '%kafaa_rule_read(%')`)).rows[0].n;
if (left) { console.error(`gen-rls-scope: ${left} policies still call kafaa_rule_read`); process.exit(1); }
console.log(`gen-rls-scope: ${n} policies rewritten; ${ids.length} identities × ${tables.length} tables identical before/after (${visible} non-empty results); policies before: ${beforeMd5}`);

const path = `supabase/migrations/${OUT}`;
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = read(path); } catch { /* missing */ }
  if (cur !== sql) {
    console.error(`gen-rls-scope: ${path} is out of date; run node scripts/gen-rls-scope.mjs`);
    process.exit(1);
  }
} else writeFileSync(path, sql);
