// Renders src/auth/policy.ts into:
//   supabase/migrations/20261008120200_kafaa_policy.sql  (kafaa_policy_matrix + identity/grant/scope/audit/ledger helpers)
//   docs/RBAC.md                                        (human-readable matrix, same data)
import { writeFileSync, mkdirSync } from 'node:fs';
import { MATRIX, PLATFORM_ROLES, RESOURCES, RESOURCE_LABELS, ROLE_LABELS, RULES, MIN_GROUP_SIZE } from '../src/auth/policy.ts';

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const res of RESOURCES) for (const role of PLATFORM_ROLES) for (const lvl of MATRIX[res][role] ?? []) rows.push(`(${lit(role)}, ${lit(res)}, ${lit(lvl)})`);

const sql = `-- Kafa'a access policy helpers
-- GENERATED by scripts/gen-policy.mjs from src/auth/policy.ts (the matrix part). Do not edit by hand.
-- Additive only. Identity comes from NEXUS: public.profiles via nexus_my_persona() / nexus_uid().

create table if not exists kafaa_policy_matrix (
  role text not null,
  resource text not null,
  level text not null check (level in ('R','Own','Scope','Agg','W','A','OwnOrg','OrgW')),
  primary key (role, resource, level)
);
comment on table kafaa_policy_matrix is '[M14] Platform access matrix (spec Section 7), generated from src/auth/policy.ts';
delete from kafaa_policy_matrix;
insert into kafaa_policy_matrix (role, resource, level) values
${rows.join(',\n')};
alter table kafaa_policy_matrix enable row level security;
drop policy if exists kafaa_read on kafaa_policy_matrix;
create policy kafaa_read on kafaa_policy_matrix for select to anon, authenticated using (true);
grant select on kafaa_policy_matrix to anon, authenticated;

-- The caller's Kafa'a person id (people.persona_id = the NEXUS persona of the JWT), or null for anonymous.
create or replace function kafaa_me() returns text language sql stable security definer set search_path = public as $$
  select p.id from kafaa_people p where p.persona_id = nexus_my_persona() and p.status <> 'leaver' limit 1
$$;

create or replace function kafaa_my_org() returns text language sql stable security definer set search_path = public as $$
  select coalesce((select p.org_id from kafaa_people p where p.id = kafaa_me()), nexus_my_org())
$$;

-- Active platform roles of the caller, always including 'public'. A leaver has none (M14: loses access in one sync cycle).
create or replace function kafaa_my_roles() returns text[] language sql stable security definer set search_path = public as $$
  select array_append(coalesce(array_agg(distinct ra.role), '{}'::text[]), 'public')
  from kafaa_role_assignments ra
  where ra.person_id = kafaa_me() and ra.status = 'active' and (ra.expires_at is null or ra.expires_at >= current_date)
$$;

create or replace function kafaa_has_grant(p_res text, p_levels text[]) returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from kafaa_policy_matrix m where m.resource = p_res and m.level = any(p_levels) and m.role = any(kafaa_my_roles()))
$$;

create or replace function kafaa_has_role(p_role text) returns boolean language sql stable security definer set search_path = public as $$
  select p_role = any(kafaa_my_roles())
$$;

-- Does the caller hold p_role AND does that role carry level p_level on p_res?
create or replace function kafaa_role_grant(p_role text, p_res text, p_level text) returns boolean language sql stable security definer set search_path = public as $$
  select kafaa_has_role(p_role) and exists (select 1 from kafaa_policy_matrix m where m.role = p_role and m.resource = p_res and m.level = p_level)
$$;

-- Is target person inside the scope of one of the caller's role assignments whose role has 'Scope' on p_res?
create or replace function kafaa_in_scope(p_res text, p_person text) returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1
    from kafaa_role_assignments ra
    join kafaa_policy_matrix m on m.role = ra.role and m.resource = p_res and m.level = 'Scope'
    join kafaa_people t on t.id = p_person
    where ra.person_id = kafaa_me() and ra.status = 'active' and (ra.expires_at is null or ra.expires_at >= current_date)
      and (
        ra.scope_type = 'all'
        or (ra.scope_type = 'entity' and t.entity_id = ra.scope_value)
        or (ra.scope_type = 'family' and t.job_family_id = ra.scope_value)
        or (ra.scope_type = 'team' and t.team_id = ra.scope_value)
        or (ra.scope_type = 'crew' and t.crew = ra.scope_value)
        or (ra.scope_type = 'org' and t.org_id = ra.scope_value)
      )
  )
$$;

-- The generic row rule used by every RLS read policy (same logic as src/data/access.ts).
create or replace function kafaa_rule_read(p_res text, p_person text, p_org text, p_where boolean) returns boolean language sql stable security definer set search_path = public as $$
  select
    (coalesce(p_where, false) and kafaa_has_grant(p_res, array['R','W','A']))
    or (p_person is not null and p_person = kafaa_me() and kafaa_has_grant(p_res, array['Own','Scope']))
    or (p_person is not null and kafaa_has_grant(p_res, array['Scope']) and kafaa_in_scope(p_res, p_person))
    or (p_org is not null and p_org = kafaa_my_org() and kafaa_has_grant(p_res, array['OwnOrg','OrgW']))
$$;

-- ───────────── Append-only, hash-chained audit log (M16). Same canonical form as src/data/audit.ts.
create or replace function kafaa_audit_canonical(p_seq integer, p_ts timestamptz, p_actor text, p_role text, p_action text, p_table text, p_entity text, p_outcome text, p_reason text)
returns text language sql immutable set search_path = public as $$
  select concat_ws('|', p_seq::text, to_char(p_ts at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'), coalesce(p_actor, ''), coalesce(p_role, ''), p_action,
                   coalesce(p_table, ''), coalesce(p_entity, ''), p_outcome, coalesce(p_reason, ''))
$$;

create or replace function kafaa_audit(p_action text, p_table text, p_entity text, p_outcome text, p_reason text,
                                       p_ledger_status text default 'not_applicable', p_ledger_seq integer default null, p_role text default null)
returns kafaa_audit_events language plpgsql security definer set search_path = public as $$
declare last kafaa_audit_events; r kafaa_audit_events; v_seq integer; v_ts timestamptz := date_trunc('second', now()); v_actor text := kafaa_me(); v_prev text;
begin
  perform pg_advisory_xact_lock(hashtext('kafaa_audit_chain'));
  select * into last from kafaa_audit_events order by seq desc limit 1;
  v_seq := coalesce(last.seq, 0) + 1;
  v_prev := coalesce(last.hash, repeat('0', 64));
  insert into kafaa_audit_events (id, seq, ts, actor_person_id, actor_role, action, entity_table, entity_id, outcome, reason, prev_hash, hash, ledger_status, ledger_seq)
  values ('AE-' || lpad(v_seq::text, 7, '0'), v_seq, v_ts, v_actor, p_role, p_action, p_table, p_entity, p_outcome, p_reason, v_prev,
          encode(sha256(convert_to(v_prev || kafaa_audit_canonical(v_seq, v_ts, v_actor, p_role, p_action, p_table, p_entity, p_outcome, p_reason), 'UTF8')), 'hex'),
          p_ledger_status, p_ledger_seq)
  returning * into r;
  return r;
end $$;

-- Verify the audit chain; returns the number of entries checked or raises at the first break.
create or replace function kafaa_audit_verify() returns integer language plpgsql stable security definer set search_path = public as $$
declare e kafaa_audit_events; prev text := repeat('0', 64); n integer := 0;
begin
  if not kafaa_has_grant('audit_log', array['R']) then raise exception 'Kafa''a · audit log is restricted' using errcode = '42501'; end if;
  for e in select * from kafaa_audit_events order by seq loop
    if e.prev_hash <> prev or e.hash <> encode(sha256(convert_to(prev || kafaa_audit_canonical(e.seq, e.ts, e.actor_person_id, e.actor_role, e.action, e.entity_table, e.entity_id, e.outcome, e.reason), 'UTF8')), 'hex') then
      raise exception 'Kafa''a · audit chain broken at seq %', e.seq;
    end if;
    prev := e.hash; n := n + 1;
  end loop;
  return n;
end $$;

-- Row-level audit for direct client writes ("every write produces an audit event"). Skipped while seeding.
create or replace function kafaa_audit_row() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if coalesce(current_setting('kafaa.seeding', true), '') = 'on' then return new; end if;
  perform kafaa_audit(lower(tg_op) || ':' || tg_table_name, tg_table_name, new.id::text, 'ok', null);
  return new;
end $$;

-- Append a material action to the NEXUS evidence ledger (plane PEOPLE by default) as the caller.
-- Uses the caller's first NEXUS role; returns the ledger seq, or null when the caller has no NEXUS profile
-- (Kafa'a-only personas) or NEXUS refuses. Never raises: the Kafa'a audit row records the outcome.
create or replace function kafaa_ledger(p_action text, p_reason text, p_plane text default 'PEOPLE', p_domain text default 'KAFAA')
returns integer language plpgsql security definer set search_path = public as $$
declare v_role text; r record;
begin
  select (roles)[1] into v_role from profiles where user_id = nexus_uid();
  if v_role is null then return null; end if;
  begin
    select * into r from nexus_append_ledger(jsonb_build_object('plane', p_plane, 'domain', p_domain, 'action', p_action,
      'evidence_class', 'USER_ACTION', 'role', v_role, 'reason', p_reason));
    return r.seq;
  exception when others then
    return null;
  end;
end $$;

revoke all on function kafaa_audit(text, text, text, text, text, text, integer, text) from public, anon, authenticated;
revoke all on function kafaa_ledger(text, text, text, text) from public, anon, authenticated;
revoke all on function kafaa_audit_row() from public, anon, authenticated;
grant execute on function kafaa_me(), kafaa_my_org(), kafaa_my_roles(), kafaa_has_grant(text, text[]), kafaa_has_role(text),
  kafaa_role_grant(text, text, text), kafaa_in_scope(text, text), kafaa_rule_read(text, text, text, boolean), kafaa_audit_verify() to anon, authenticated;

-- Business constants shared with src/auth/policy.ts RULES
create or replace function kafaa_rules() returns jsonb language sql immutable set search_path = public as $$ select ${lit(JSON.stringify({ ...RULES, minGroupSize: MIN_GROUP_SIZE }))}::jsonb $$;
grant execute on function kafaa_rules() to anon, authenticated;
`;

const codes = (r, res) => (MATRIX[res][r] ?? []).join(' ') || '·';
let md = `# Kafa'a platform access matrix\n\nGenerated from \`src/auth/policy.ts\` by \`scripts/gen-policy.mjs\`. The same table is loaded into \`kafaa_policy_matrix\` (Supabase) and enforced by the LocalBackend.\n\nCodes: · none · R read · Own own records · Scope records in the user's assigned scope · Agg aggregate only (groups under ${MIN_GROUP_SIZE} suppressed) · W create/edit · A approve/decide · OwnOrg own organisation's records · OrgW write own organisation's records. [K] = Kafa'a addition to the spec matrix.\n\n`;
md += `| Resource | ${PLATFORM_ROLES.map((r) => ROLE_LABELS[r].en).join(' | ')} |\n|${'---|'.repeat(PLATFORM_ROLES.length + 1)}\n`;
for (const res of RESOURCES) md += `| ${RESOURCE_LABELS[res]} (\`${res}\`) | ${PLATFORM_ROLES.map((r) => codes(r, res)).join(' | ')} |\n`;
mkdirSync('docs', { recursive: true });
writeFileSync('supabase/migrations/20261008120200_kafaa_policy.sql', sql);
writeFileSync('docs/RBAC.md', md);
console.log(`gen-policy: ${rows.length} matrix rows`);
